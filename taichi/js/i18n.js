export function normalizeLanguage(value) {
  const tag = String(value || '').replace(/_/g, '-').toLowerCase();
  if (tag.startsWith('zh')) return /(?:cn|sg|hans)/.test(tag) ? 'zh-CN' : 'zh-TW';
  const base = tag.split('-')[0];
  return supportedLanguages.includes(base) ? base : null;
}
export function detectLanguage() {
  try {
    const saved = localStorage.getItem('smartaction-language');
    if (supportedLanguages.includes(saved)) return saved;
  } catch { /* Storage may be unavailable for local files/private browsing. */ }
  const candidates = typeof navigator === 'undefined' ? [] : (navigator.languages?.length ? navigator.languages : [navigator.language]);
  for (const locale of candidates) { const match = normalizeLanguage(locale); if (match) return match; }
  return 'en';
}
export function t(key, lang = 'zh-TW', vars = {}) {
  const locale = messages[lang] ? lang : normalizeLanguage(lang) || 'en';
  const value = messages[locale]?.[key] ?? messages.en[key] ?? key;
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (whole, name) => Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole);
}
export function applyLanguage(lang, root = document) {
  lang = messages[lang] ? lang : normalizeLanguage(lang) || 'en';
  root.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n, lang); });
  root.querySelectorAll('[data-i18n-title]').forEach(element => { const translated = t(element.dataset.i18nTitle, lang); element.title = translated; element.setAttribute('aria-label', translated); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder, lang); });
  root.querySelectorAll('[data-i18n-aria]').forEach(element => { element.setAttribute('aria-label', t(element.dataset.i18nAria, lang)); });
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.title = `${t('brand', lang)} | SmartAction`;
    document.querySelectorAll('#closeMapBtn,#closeHelpBtn').forEach(button => button.setAttribute('aria-label', t('close', lang)));
    const select = document.getElementById('language');
    if (select) {
      if (select.options.length !== supportedLanguages.length) select.replaceChildren(...supportedLanguages.map(value => {const option=document.createElement('option');option.value=value;option.textContent=languageNames[value];return option;}));
      select.value = lang;
    }
  }
  try { localStorage.setItem('smartaction-language', lang); } catch { /* Optional preference. */ }
  return lang;
}
